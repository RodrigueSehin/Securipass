/** Modules génériques à partir d'une liste de titres : 4 leçons par module, durée répartie sur la durée totale. */
function modulesFrom(titles, totalMinutes) {
  const perLesson = Math.max(10, Math.round(totalMinutes / (titles.length * LESSON_TEMPLATES.length) / 5) * 5);
  return titles.map((title) => ({
    title,
    lessons: LESSON_TEMPLATES.map((t) => ({ title: `${t} : ${title.toLowerCase()}`, minutes: perLesson })),
  }));
}

